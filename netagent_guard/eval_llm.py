"""v6 evaluation with LLM-generated actions and LLM intent extraction. Writes into results_v6/<model>/.

Same scenarios, seeds, calibration seed (999), budgets, bootstrap and guards as results/, except that the
proposed action of every scenario is generated by the LLM agent from intent + ticket + telemetry and harm labels
are recomputed by the oracle for that action. Calls are cached in JSONL (also the action log) so a rerun with
the same model re-uses them; delete the files to force new calls."""
from __future__ import annotations

import copy
import datetime as dt
import json
import os
import subprocess
import time
from concurrent.futures import ThreadPoolExecutor

import pandas as pd

from .agent import propose_action
from .eval import CALIB_SEED, LABELS, N_SCEN, NOISE, SEEDS, analyze, raw_scores
from .guards import llm_parse_intent, parse_accuracy, parse_intent_deterministic
from .llm import Client, LLMUnavailable
from .scenarios import generate, label_scenarios

PCOLS = ["action", "elements", "slices", "max_degradation", "param_range", "all"]


def _load(path, key):
    out = {}
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            r = json.loads(line)
            if r.get("error_llm") is None:
                out[r[key]] = r
    return out


def _pmap(fn, items, workers):
    with ThreadPoolExecutor(workers) as ex:
        return list(ex.map(fn, items))


def run(out_root="results_v6", seeds=SEEDS, n=N_SCEN, workers=8, limit=None):
    client = Client()
    tag = client.model.replace("/", "__")
    out = os.path.join(out_root, tag)
    os.makedirs(out, exist_ok=True)
    t0 = time.time()
    worlds = {}
    for s in [CALIB_SEED] + list(seeds):
        st, sc = generate(s, n, include_held_out=s != CALIB_SEED)
        worlds[s] = (st, sc[:limit] if limit else sc)
    all_sc = [x for s in worlds for x in worlds[s][1]]

    # ---- 1. intent extraction (trusted intent text only)
    ipath = os.path.join(out, "llm_intents.jsonl")
    icache = _load(ipath, "text")
    todo = sorted({x["intent_text"] for x in all_sc} - set(icache))
    with open(ipath, "a", encoding="utf-8") as fh:
        def f(text):
            return {"text": text, "parsed": llm_parse_intent(text, client), "model": client.model}
        for r in _pmap(f, todo, workers):
            fh.write(json.dumps(r, ensure_ascii=False) + "\n"); icache[r["text"]] = r
    prow = []
    for x in all_sc:
        if x["seed"] == CALIB_SEED:
            continue
        for parser, p in [("keyword", parse_intent_deterministic(x["intent_text"])),
                          ("llm", icache[x["intent_text"]]["parsed"])]:
            prow.append({"parser": parser, "style": x["style"], "style_held_out": x["style_held_out"],
                         **parse_accuracy(p, x["intent"])})
    pa = pd.DataFrame(prow)
    acc = pa.groupby(["parser", "style", "style_held_out"])[PCOLS].mean()
    acc["n"] = pa.groupby(["parser", "style", "style_held_out"]).size()
    acc.reset_index().to_csv(os.path.join(out, "parser_accuracy.csv"), index=False)

    # ---- 2. LLM agent proposes the actions
    apath = os.path.join(out, "agent_actions.jsonl")
    acache = _load(apath, "scenario")
    todo = [x for x in all_sc if x["id"] not in acache]
    with open(apath, "a", encoding="utf-8") as fh:
        for r in _pmap(lambda x: propose_action(x, client, fh), todo, workers):
            acache[r["scenario"]] = r

    agent_rows, variants = [], {"keyword_parser": {}, "llm_parser": {}}
    for s, (st, sc) in worlds.items():
        new = copy.deepcopy(sc)
        for x in new:
            r = acache[x["id"]]
            agent_rows.append({"seed": s, "id": x["id"], "category": x["category"], "template": x["template"],
                               "error": r["error"], "same_as_replayed": r["action"] == x["action"],
                               "action_name": r["action"]["name"]})
            x["action_replayed_v5"], x["action"] = x["action"], r["action"]
        label_scenarios(st, new)
        for vname in variants:
            vs = copy.deepcopy(new)
            if vname == "llm_parser":
                for x in vs:
                    x["parsed_intent"] = icache[x["intent_text"]]["parsed"]
            variants[vname][s] = (st, vs)
    ag = pd.DataFrame(agent_rows)
    ag.to_csv(os.path.join(out, "agent_actions_summary.csv"), index=False)
    ag.groupby(["category", "template"]).agg(n=("id", "size"), invalid=("error", lambda e: int(e.notna().sum())),
                                             same_as_replayed=("same_as_replayed", "mean")).reset_index().to_csv(
        os.path.join(out, "agent_by_template.csv"), index=False)

    # ---- 3. guards, calibrated on seed 999 (frozen), evaluated on eval seeds
    thr_all = {}
    for vname, wd in variants.items():
        vout = os.path.join(out, vname)
        os.makedirs(vout, exist_ok=True)
        cst, csc = wd[CALIB_SEED]
        cdf = raw_scores(cst, csc, NOISE, CALIB_SEED + 1000)
        df = pd.concat([raw_scores(wd[s][0], wd[s][1], NOISE, s + 1000) for s in seeds], ignore_index=True)
        df.to_csv(os.path.join(vout, "scores.csv"), index=False)
        with open(os.path.join(vout, "scenarios.jsonl"), "w", encoding="utf-8") as fh:
            for s in seeds:
                for x in wd[s][1]:
                    fh.write(json.dumps(x, default=str, ensure_ascii=False) + "\n")
        thr_all[vname] = {t: {str(b): v for b, v in analyze(df, cdf, lab, vout, t, seeds).items()}
                          for t, lab in LABELS.items()}
        n_counts = {"n_total": int(len(df)), "n_harmful_v2": int(df.harmful_v2.sum()),
                    "n_legit_v2": int(((~df.harmful_v2) & (df.category == "benign")).sum())}
        thr_all[vname]["counts"] = n_counts
    try:
        commit = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
        dirty = bool(subprocess.run(["git", "status", "--porcelain", "--", "netagent_guard"],
                                    capture_output=True, text=True).stdout.strip())
    except OSError:
        commit, dirty = "unknown", None
    meta = {"model": client.model, "base_url": client.cfg["LLM_BASE_URL"], "temperature": 0.0,
            "run_date_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
            "git_commit": commit, "git_dirty_package": dirty, "seeds": list(seeds), "calibration_seed": CALIB_SEED,
            "n_per_seed": n, "limit": limit, "twin_noise": NOISE, "bootstrap_B": 2000,
            "usage_this_run": client.usage, "n_cached_actions": len(acache), "n_cached_intents": len(icache),
            "thresholds": thr_all, "runtime_s": round(time.time() - t0, 1)}
    json.dump(meta, open(os.path.join(out, "run_meta.json"), "w"), indent=2, default=float)
    return meta


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=None, help="first N scenarios per seed (smoke test)")
    ap.add_argument("--seeds", type=int, nargs="*", default=SEEDS)
    a = ap.parse_args()
    try:
        m = run(seeds=a.seeds, limit=a.limit)
    except LLMUnavailable as e:
        raise SystemExit(f"LLM endpoint failed, evaluation stopped: {e}")
    print(json.dumps({k: m[k] for k in ("model", "usage_this_run", "runtime_s")}, indent=1))
