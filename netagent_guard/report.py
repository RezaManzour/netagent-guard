"""Render markdown tables from results/ (and results_mvp1/ for before/after) into README.md."""
from __future__ import annotations

import json
import os

import pandas as pd

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
GUARDS = ["none", "rule", "intent", "twin", "combined"]


def _p(x):
    return "n/a" if pd.isna(x) else f"{100 * x:.1f}%"


def _main_table(m, lat=None):
    L = ["| guard | thr | harmful-exec [95% CI] | false-block [95% CI] | escalation | injected executed | task success |"
         + (" p50/p95 ms |" if lat is not None else ""),
         "|---|---|---|---|---|---|---|" + ("---|" if lat is not None else "")]
    for _, r in m.iterrows():
        row = (f"| {r.guard} | {r.threshold:g} | {_p(r.harmful_exec_rate)} [{_p(r.her_ci_lo)}, {_p(r.her_ci_hi)}] | "
               f"{_p(r.false_block_rate)} [{_p(r.fbr_ci_lo)}, {_p(r.fbr_ci_hi)}] | {_p(r.escalation_rate)} | "
               f"{_p(r.injected_exec_rate)} | {_p(r.task_success)} |")
        if lat is not None:
            row += (f" {lat.loc[r.guard].p50:.2f} / {lat.loc[r.guard].p95:.2f} |" if r.guard in lat.index else " - |")
        L.append(row)
    return L


def tables(out_dir="results", before_dir="results_mvp1") -> str:
    s = json.load(open(f"{out_dir}/summary.json"))
    c = s["config"]
    lat = pd.read_csv(f"{out_dir}/latency.csv").set_index("guard")
    L = [f"_Generated by `python run_all.py` from `{out_dir}/` (runtime {s['runtime_s']} s). Eval seeds {c['seeds']}, "
         f"{c['n_per_seed']} scenarios/seed = {c['n_total']}; harmful: {c['n_harmful_v2']} (v2) / {c['n_harmful_v1']} (v1); "
         f"legitimate (v2): {c['n_legit_v2']}. Thresholds calibrated on seed {c['calibration_seed']} (no held-out "
         f"injection templates, no held-out intent styles) per false-block budget, then frozen. Twin noise "
         f"{c['twin_noise']}. CI = bootstrap B={c['bootstrap_B']} over pooled scenarios._", ""]
    for tag, title in [("v2", "Harm v2 (primary: independent harm on hidden true network)"),
                       ("v1", "Harm v1 (scope-relative, shares the twin guard's rule family)")]:
        m = pd.read_csv(f"{out_dir}/main_metrics_{tag}.csv")
        L += [f"### {title} - calibrated at false-block <= 5%", ""]
        L += _main_table(m[(m.budget == 0.05) & m.guard.isin(GUARDS)], lat)
        L += ["", f"#### {tag}: calibrated thresholds at each false-block budget (budget set on calibration seed; "
                  "realised eval false-block shown)", "",
              "| guard | budget 1%: HER / FBR / esc | budget 5% | budget 10% |", "|---|---|---|---|"]
        for g in GUARDS:
            cells = []
            for b in [0.01, 0.05, 0.10]:
                r = m[(m.budget == b) & (m.guard == g)].iloc[0]
                cells.append(f"{_p(r.harmful_exec_rate)} / {_p(r.false_block_rate)} / {_p(r.escalation_rate)}")
            L.append(f"| {g} | " + " | ".join(cells) + " |")
        mf = pd.read_csv(f"{out_dir}/matched_fbr_oracle_{tag}.csv")
        L += ["", f"#### {tag}: matched false-block, best threshold chosen on the eval sweep (optimistic for every guard)", "",
              "| guard | FBR<=1% | FBR<=5% | FBR<=10% |", "|---|---|---|---|"]
        for g in GUARDS:
            sub = mf[mf.guard == g]
            L.append(f"| {g} | " + " | ".join(_p(x) for x in sub.harmful_exec_rate) + " |")
        L.append("")
    m = pd.read_csv(f"{out_dir}/main_metrics_v2.csv")
    m5 = m[m.budget == 0.05]
    L += ["### v2 breakdown at the 5% budget (incl. ablations)", "",
          "| guard | HER inj. I1-I4 | HER inj. held-out I5-I7 | HER erroneous | FBR train styles | FBR held-out styles | HER held-out styles |",
          "|---|---|---|---|---|---|---|"]
    for _, r in m5.iterrows():
        L.append(f"| {r.guard} | {_p(r.her_injected_train)} | {_p(r.her_injected_heldout)} | {_p(r.her_erroneous)} | "
                 f"{_p(r.fbr_train_styles)} | {_p(r.fbr_heldout_styles)} | {_p(r.her_heldout_styles)} |")
    L += ["", "Ablation rows: `comb-no_X` removes component X; `comb-escalate_unparsed` escalates when the intent cannot be parsed.", ""]
    pa = pd.read_csv(f"{out_dir}/parser_accuracy.csv")
    L += ["### Deterministic intent-parser accuracy (eval seeds)", "",
          "| style | held-out | n | action | elements | slices | max-deg | param range | all fields |",
          "|---|---|---|---|---|---|---|---|---|"]
    for _, r in pa.iterrows():
        L.append(f"| {r['style']} | {r.style_held_out} | {r.n} | {_p(r.parse_action)} | {_p(r.parse_elements)} | {_p(r.parse_slices)} | "
                 f"{_p(r.parse_max_degradation)} | {_p(r.parse_param_range)} | {_p(r.parse_all)} |")
    ag = pd.read_csv(f"{out_dir}/label_agreement.csv")
    L += ["", f"### Label agreement v1 vs v2 (rows v1, columns v2)", "", "| v1 \\ v2 | False | True |", "|---|---|---|"]
    for _, r in ag.iterrows():
        L.append(f"| {r.harmful_v1} | {r['False']} | {r['True']} |")
    L += ["", f"v2 harm-reason counts (one scenario can have several): {s['harm_reason_counts_v2']}", ""]
    mc = pd.read_csv(f"{out_dir}/mcnemar_v2.csv")
    mc = mc[mc.budget == 0.05]
    L += ["### McNemar exact tests (v2, 5% budget)", "", "| A | B | subset | A bad & B ok | A ok & B bad | p |", "|---|---|---|---|---|---|"]
    for _, r in mc.iterrows():
        L.append(f"| {r.guard_a} | {r.guard_b} | {r.subset} | {r.a_bad_b_ok} | {r.a_ok_b_bad} | {r.p_value:.3g} |")
    nz = pd.read_csv(f"{out_dir}/noise_ablation.csv")
    L += ["", "### Twin-fidelity ablation (v2, 5%-budget thresholds)", "", "| noise | guard | harmful-exec | false-block | escalation |", "|---|---|---|---|---|"]
    for _, r in nz.iterrows():
        L.append(f"| {r.noise:g} | {r.guard} | {_p(r.harmful_exec_rate)} | {_p(r.false_block_rate)} | {_p(r.escalation_rate)} |")
    if os.path.exists(f"{before_dir}/main_metrics.csv"):
        b = pd.read_csv(f"{before_dir}/main_metrics.csv").set_index("guard")
        L += ["", "### Before / after hardening", "",
              f"Before = first MVP run (`{before_dir}/`: harm v1 only, templated intents, weaker rules, FBR budget 10%). "
              "After = this run, harm v2, 5% budget.", "",
              "| guard | before HER | before FBR | before esc | after HER | after FBR | after esc |", "|---|---|---|---|---|---|---|"]
        for g in GUARDS:
            a = m5[m5.guard == g].iloc[0]
            L.append(f"| {g} | {_p(b.loc[g].harmful_exec_rate)} | {_p(b.loc[g].false_block_rate)} | {_p(b.loc[g].escalation_rate)} | "
                     f"{_p(a.harmful_exec_rate)} | {_p(a.false_block_rate)} | {_p(a.escalation_rate)} |")
    L += ["", "Plots: `results/tradeoff_v2.png`, `results/tradeoff_v1.png`, `results/main_bars.png`, `results/noise_ablation.png`."]
    return "\n".join(L)


def update_readme(path="README.md", out_dir="results"):
    t = tables(out_dir)
    open(f"{out_dir}/tables.md", "w").write(t + "\n")
    s = open(path).read()
    a, b = s.index(START) + len(START), s.index(END)
    open(path, "w").write(s[:a] + "\n" + t + "\n" + s[b:])
